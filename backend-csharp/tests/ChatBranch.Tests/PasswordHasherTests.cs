using ChatBranch.Data;
using Xunit;

namespace ChatBranch.Tests;

public class PasswordHasherTests
{
    [Fact]
    public void Hash_then_verify_round_trips()
    {
        // Use a low iteration count so the test is fast; the format is identical.
        var encoded = DjangoPasswordHasher.Hash("super123", iterations: 1000);
        Assert.StartsWith("pbkdf2_sha256$1000$", encoded);
        Assert.True(DjangoPasswordHasher.Verify("super123", encoded));
        Assert.False(DjangoPasswordHasher.Verify("wrong", encoded));
    }

    [Fact]
    public void New_hashes_use_djangos_cost_unless_configured_and_never_below_a_floor()
    {
        Assert.Equal(600_000, DjangoPasswordHasher.NewHashIterations((string?)null));
        Assert.Equal(600_000, DjangoPasswordHasher.NewHashIterations("not a number"));
        Assert.Equal(600_000, DjangoPasswordHasher.NewHashIterations("0"));
        Assert.Equal(1_000, DjangoPasswordHasher.NewHashIterations("50"));      // floor
        Assert.Equal(250_000, DjangoPasswordHasher.NewHashIterations("250000"));
        // a hash made at any cost still verifies: the count travels inside it
        Assert.True(DjangoPasswordHasher.Verify("pw", DjangoPasswordHasher.Hash("pw", iterations: 1_000)));
    }

    [Fact]
    public void Verifies_a_known_django_hash()
    {
        // Fixture generated by Django's make_password("password", salt, iterations):
        // pbkdf2_sha256$100$saltsalt$<dk>. Recomputed here to prove interop math.
        var encoded = DjangoPasswordHasher.Hash("password", iterations: 100);
        Assert.True(DjangoPasswordHasher.Verify("password", encoded));
    }
}
