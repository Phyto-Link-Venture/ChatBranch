namespace ChatBranch.Domain;

// Files the AI (or an operator) generated for a conversation through a
// "Connected app" skill — PDF invoices, quotations, receipts and letters
// (app "documents") and QR codes (app "qr"). Like a calendar booking, an AI
// document is RESERVED while the reply is written (status pending: the number
// is taken, the file rendered and stored as conversation media) and SENT as a
// file right after the reply text when the reply is delivered. A reply that is
// never delivered (rejected, expired, shadowed, blocked) VOIDS it — the number
// stays used, so the sequence never has silent gaps.

public static class DocumentTypes
{
    public const string Invoice = "invoice";
    public const string Quotation = "quotation";
    public const string Receipt = "receipt";
    public const string Letter = "letter";
    public const string Qr = "qr";

    /// <summary>The numbered PDF types (a QR code has no running number).</summary>
    public static readonly string[] Numbered = { Invoice, Quotation, Receipt, Letter };
    public static readonly string[] All = { Invoice, Quotation, Receipt, Letter, Qr };

    public static string Label(string type) => type switch
    {
        Invoice => "Invoice",
        Quotation => "Quotation",
        Receipt => "Receipt",
        Letter => "Letter",
        Qr => "QR code",
        _ => "Document",
    };
}

public static class DocumentStatus
{
    /// <summary>Made by an AI reply that has not been delivered yet (number taken, file ready).</summary>
    public const string Pending = "pending";
    /// <summary>Sent to the customer (as a file, or as a download link on a channel without files).</summary>
    public const string Sent = "sent";
    /// <summary>Its reply was never delivered (rejected, expired, shadowed, blocked) — kept for the number.</summary>
    public const string Void = "void";
    /// <summary>Delivery tried to send it and the channel refused.</summary>
    public const string Failed = "failed";
    /// <summary>Generated by hand and kept (an operator's "Create document" without sending).</summary>
    public const string Issued = "issued";

    public static readonly string[] All = { Pending, Sent, Void, Failed, Issued };
}

public class Document : IEntityScoped
{
    public int Id { get; set; }
    /// <summary>The conversation's entity (ScopeOwned reads, like threads and bookings).</summary>
    public int? EntityId { get; set; }
    public int? ContactId { get; set; }
    public int? ThreadId { get; set; }
    /// <summary>The app skill (AgentSkill.SkillId) that made it; "" when an operator made it by hand.</summary>
    public string SkillId { get; set; } = "";
    /// <summary><see cref="DocumentTypes"/>.</summary>
    public string Type { get; set; } = DocumentTypes.Invoice;
    /// <summary>The running-number series: <c>&lt;skill id | entity:id | org&gt;:&lt;type&gt;</c>.</summary>
    public string Series { get; set; } = "";
    /// <summary>The number within the series (0 for a QR code).</summary>
    public int Seq { get; set; }
    /// <summary>"INV-0012" — prefix + zero-padded seq ("" for a QR code).</summary>
    public string Number { get; set; } = "";
    public string Title { get; set; } = "";
    public string Currency { get; set; } = "";
    public decimal Subtotal { get; set; }
    public decimal Discount { get; set; }
    public decimal Tax { get; set; }
    public decimal Total { get; set; }
    /// <summary>What was rendered (lines, customer, notes…) — snake_case JSON.</summary>
    public Dictionary<string, object?> Data { get; set; } = new();
    /// <summary>The stored file, relative to the channel's media root (<c>MediaStore</c>).</summary>
    public string FilePath { get; set; } = "";
    /// <summary>The channel whose media root holds <see cref="FilePath"/>.</summary>
    public string FileChannel { get; set; } = "";
    public string FileName { get; set; } = "";
    public string Mime { get; set; } = "application/pdf";
    public long SizeBytes { get; set; }
    /// <summary><see cref="DocumentStatus"/>.</summary>
    public string Status { get; set; } = DocumentStatus.Pending;
    /// <summary><c>ai</c> or <c>agent:&lt;username&gt;</c>.</summary>
    public string CreatedBy { get; set; } = "ai";
    /// <summary>The AI draft whose delivery sends it.</summary>
    public int? DraftId { get; set; }
    /// <summary>The message that carried the file (or the link).</summary>
    public int? MessageId { get; set; }
    /// <summary>128-bit random token for the customer's download link (channels without files).</summary>
    public string PublicToken { get; set; } = "";
    /// <summary>Why it was voided / failed, or how it was sent ("file" | "link").</summary>
    public string Detail { get; set; } = "";
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }
    public DateTime? SentAt { get; set; }
}
